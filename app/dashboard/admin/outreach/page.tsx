import { getOutreachEmails } from '@/lib/db/queries'
import { Card, CardHeader, CardTitle, CardContent } from '@/components/ui/card'
import { Badge } from '@/components/ui/badge'
import { ExternalLink, Mail } from 'lucide-react'

export default async function OutreachAdminPage() {
    const emails = await getOutreachEmails()

    return (
        <div className="p-8">
            <div className="flex items-center justify-between mb-8">
                <div>
                    <h1 className="text-3xl font-bold flex items-center gap-3">
                        <span className="text-pink-500">🏹</span> Agent Artemis Logs
                    </h1>
                    <p className="text-gray-500 mt-2">View automated backlink outreach campaigns generated by Artemis.</p>
                </div>
            </div>

            <div className="space-y-6">
                {emails.length === 0 ? (
                    <Card>
                        <CardContent className="flex flex-col items-center justify-center p-12 text-gray-500">
                            <Mail className="w-12 h-12 mb-4 text-gray-300" />
                            <p>No outreach emails have been sent yet.</p>
                            <p className="text-sm mt-2">Agent Artemis will log her campaigns here.</p>
                        </CardContent>
                    </Card>
                ) : (
                    emails.map((email: any) => (
                        <Card key={email.id} className="overflow-hidden border-pink-100 dark:border-pink-900/30">
                            <CardHeader className="bg-pink-50/50 dark:bg-pink-900/10 pb-4 border-b border-pink-100 dark:border-pink-900/30">
                                <div className="flex justify-between items-start">
                                    <div>
                                        <CardTitle className="text-lg mb-1">{email.subject}</CardTitle>
                                        <div className="flex items-center gap-4 text-sm text-gray-500">
                                            <span className="flex items-center gap-1">
                                                <Mail className="w-4 h-4" /> To: {email.target_email}
                                            </span>
                                            <span className="flex items-center gap-1">
                                                <ExternalLink className="w-4 h-4" /> Target: {email.target_url}
                                            </span>
                                        </div>
                                    </div>
                                    <div className="flex flex-col items-end gap-2">
                                        <Badge variant={email.status === 'sent' ? 'default' : 'secondary'} className={email.status === 'sent' ? 'bg-pink-500' : ''}>
                                            {email.status.toUpperCase()}
                                        </Badge>
                                        <span className="text-xs text-gray-400">
                                            {new Date(email.created_at).toLocaleString()}
                                        </span>
                                    </div>
                                </div>
                            </CardHeader>
                            <CardContent className="p-6">
                                <div className="prose prose-sm max-w-none text-gray-700 dark:text-gray-300" 
                                    dangerouslySetInnerHTML={{ __html: email.body }} 
                                />
                            </CardContent>
                        </Card>
                    ))
                )}
            </div>
        </div>
    )
}
